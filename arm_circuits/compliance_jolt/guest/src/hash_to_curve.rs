const DST: &[u8] = b"QUUX-V01-CS02-with-secp256k1_XMD:SHA-256_SSWU_RO_";

// Helper: construct Fq from 32 big-endian bytes (may be >= p, but field ops will reduce)
fn fq_from_be32(bytes: &[u8; 32]) -> Fq {
    // Convert BE bytes to LE u64 limbs
    let limbs = [
        u64::from_be_bytes([bytes[24], bytes[25], bytes[26], bytes[27], bytes[28], bytes[29], bytes[30], bytes[31]]),
        u64::from_be_bytes([bytes[16], bytes[17], bytes[18], bytes[19], bytes[20], bytes[21], bytes[22], bytes[23]]),
        u64::from_be_bytes([bytes[8],  bytes[9],  bytes[10], bytes[11], bytes[12], bytes[13], bytes[14], bytes[15]]),
        u64::from_be_bytes([bytes[0],  bytes[1],  bytes[2],  bytes[3],  bytes[4],  bytes[5],  bytes[6],  bytes[7]]),
    ];
    Fq::from_u64_arr_unchecked(&limbs)
}

// Reduce 48 big-endian bytes to Fq: value = high_128 * 2^256 + low_256
fn fq_from_be48(bytes: &[u8]) -> Fq {
    // 2^256 mod p = 0x1000003D1 (for secp256k1)
    let f_2_256 = Fq::from_u64_arr_unchecked(&[0x1000003D1, 0, 0, 0]);

    // high = bytes[0..16] as u128, stored as Fq
    let mut high_bytes = [0u8; 32];
    high_bytes[16..32].copy_from_slice(&bytes[0..16]);
    let high = fq_from_be32(&high_bytes);

    // low = bytes[16..48] as 256-bit
    let mut low_bytes = [0u8; 32];
    low_bytes.copy_from_slice(&bytes[16..48]);
    let low = fq_from_be32(&low_bytes);

    // Reduce: add performs mod p
    high.mul(&f_2_256).add(&low)
}

fn one() -> Fq { Fq::from_u64_arr_unchecked(&[1, 0, 0, 0]) }

fn fq_const(bytes: &[u8; 32]) -> Fq { fq_from_be32(bytes) }

