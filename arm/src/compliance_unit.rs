//! Host/zkVM engine operations on [`ComplianceUnit`]: proving,
//! verification, and journal decoding. The type itself lives in
//! `anoma-rm-core` and is re-exported here unchanged.

pub use arm_core::compliance_unit::*;

use crate::{
    compliance::ComplianceInstance,
    constants::COMPLIANCE_VK,
    error::ArmError,
    proving_system::{journal_to_instance, verify as verify_proof},
};
use k256::ProjectivePoint;
use risc0_zkvm::InnerReceipt;

#[cfg(feature = "prove")]
use crate::{
    compliance::ComplianceWitness,
    constants::COMPLIANCE_PK,
    proving_system::{prove, ProofType},
};

/// Creates a new compliance unit by proving the given witness.
/// Proving key and verifying key are constants, so we don't need to pass
/// them as parameters. Instance is generated by proving.
#[cfg(feature = "prove")]
pub fn create(
    witness: &ComplianceWitness,
    proof_type: ProofType,
) -> Result<ComplianceUnit, ArmError> {
    let (proof, instance) = prove(COMPLIANCE_PK, witness, proof_type)?;
    Ok(ComplianceUnit { proof, instance })
}

/// Verifies the compliance proof against the instance using the constant verifying key.
pub fn verify(unit: &ComplianceUnit) -> Result<(), ArmError> {
    verify_proof(&COMPLIANCE_VK, &unit.instance, &unit.proof)
}

/// Obtains the delta from the compliance instance.
pub fn delta(unit: &ComplianceUnit) -> Result<ProjectivePoint, ArmError> {
    crate::compliance::delta_projective(&get_instance(unit)?)
}

/// Retrieves the compliance instance from the serialized instance data.
pub fn get_instance(unit: &ComplianceUnit) -> Result<ComplianceInstance, ArmError> {
    journal_to_instance(&unit.instance)
}

/// Retrieves the inner receipt from the compliance proof.
pub fn get_inner_receipt(unit: &ComplianceUnit) -> Result<InnerReceipt, ArmError> {
    bincode::deserialize(&unit.proof).map_err(|_| ArmError::InnerReceiptDeserializationError)
}
