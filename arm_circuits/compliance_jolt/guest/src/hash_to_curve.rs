/// ExpandMsgXmd<SHA-256> → field elements
pub fn hash_to_field(msg: &[u8], count: usize) -> Vec<Fq> {
    use crate::digest::hash_bytes;
    let dst_len = DST.len() as u8;
    let len_in_bytes = count * 48;

    let mut msg_prime = Vec::new();
    msg_prime.extend_from_slice(&[0u8; 64]); // Z_pad
    msg_prime.extend_from_slice(msg);
    msg_prime.push((len_in_bytes >> 8) as u8);
    msg_prime.push(len_in_bytes as u8);
    msg_prime.push(0u8);
    msg_prime.extend_from_slice(DST);
    msg_prime.push(dst_len);
    let b_0 = hash_bytes(&msg_prime);

    let mut b_vals: Vec<Vec<u8>> = Vec::new();
    let mut tmp = Vec::new();
    tmp.extend_from_slice(b_0.as_bytes());
    tmp.push(1u8);
    tmp.extend_from_slice(DST);
    tmp.push(dst_len);
    b_vals.push(hash_bytes(&tmp).as_bytes().to_vec());

    for i in 2..=(len_in_bytes / 32 + 1) {
        let mut tmp = Vec::new();
        let prev = &b_vals[b_vals.len() - 1];
        for j in 0..32 { tmp.push(b_0.as_bytes()[j] ^ prev[j]); }
        tmp.push(i as u8);
        tmp.extend_from_slice(DST);
        tmp.push(dst_len);
        b_vals.push(hash_bytes(&tmp).as_bytes().to_vec());
    }

    let mut uniform_bytes = Vec::new();
    for b in &b_vals { uniform_bytes.extend_from_slice(b); }

    let mut result = Vec::new();
    for i in 0..count {
        let chunk = &uniform_bytes[i * 48..(i + 1) * 48];
        result.push(fq_from_be48(chunk));
    }
    result
}

fn is_odd(x: &Fq) -> bool { x.e()[0] & 1 == 1 }

fn invert(x: &Fq) -> Fq { one().div(x) }

fn osswu(u: &Fq) -> (Fq, Fq) {
    let a = map_a();
    let b = map_b();
    let z = z_param();
    let c2 = c2_param();

    let tv1 = u.square();
    let tv3 = z.mul(&tv1);
    let tv2 = tv3.square();
    let xd_sum = tv2.add(&tv3);
    let x1n = b.mul(&xd_sum.add(&one()));
    let mut xd = xd_sum.mul(&a.neg());

    if xd.is_zero() { xd = z.mul(&a); }

    let tv2 = xd.square();
    let gxd = tv2.mul(&xd);
    let tv2 = tv2.mul(&a);

    let mut gx1 = x1n.mul(&tv2.add(&x1n.square()));
    let tv2 = gxd.mul(&b);
    gx1 = gx1.add(&tv2);

    let tv4 = gxd.square();
    let tv2 = gx1.mul(&gxd);
    let tv4 = tv4.mul(&tv2);

    let y1 = pow_c1(&tv4).mul(&tv2);
    let x2n = tv3.mul(&x1n);
    let y2 = y1.mul(&c2).mul(&tv1).mul(u);

    let tv2 = y1.square().mul(&gxd);
    let e2 = tv2.e() == gx1.e(); // equality check via limbs

    let mut x = if e2 { x1n } else { x2n };
    x = x.mul(&invert(&xd));
    let mut y = if e2 { y1 } else { y2 };

    if is_odd(u) != is_odd(&y) { y = y.neg(); }
    (x, y)
}

fn isogeny(rx: Fq, ry: Fq) -> (Fq, Fq) {
    let xn = xnum();
    let xd = xden();
    let yn = ynum();
    let yd = yden();
    let x_num = horner(&xn, &rx);
    let x_den = horner(&xd, &rx);
    let y_num = horner(&yn, &rx);
    let y_den = horner(&yd, &rx);
    let qx = x_num.mul(&invert(&x_den));
    let qy = ry.mul(&y_num).mul(&invert(&y_den));
    (qx, qy)
}

fn horner(coeffs: &[Fq], x: &Fq) -> Fq {
    let mut result = coeffs[coeffs.len() - 1].clone();
    for i in (0..coeffs.len() - 1).rev() {
        result = result.mul(x).add(&coeffs[i]);
    }
    result
}

/// x^((p-3)/4)
fn pow_c1(x: &Fq) -> Fq {
    let c1: [u64; 4] = [0xffff_ffff_bfff_ff0b, 0xffff_ffff_ffff_ffff, 0xffff_ffff_ffff_ffff, 0x3fff_ffff_ffff_ffff];
    let mut result = one();
    let mut base = x.clone();
    for limb in c1 {
        let mut bits = limb;
        for _ in 0..64 {
            if bits & 1 == 1 { result = result.mul(&base); }
            base = base.square();
            bits >>= 1;
        }
    }
    result
}

/// Full hash-to-curve
pub fn hash_to_curve(msg: &[u8]) -> Secp256k1Point {
    let u = hash_to_field(msg, 2);
    let (rx0, ry0) = osswu(&u[0]);
    let (qx0, qy0) = isogeny(rx0, ry0);
    let (rx1, ry1) = osswu(&u[1]);
    let (qx1, qy1) = isogeny(rx1, ry1);

    let p0 = Secp256k1Point::from_u64_arr(&[qx0.e()[0], qx0.e()[1], qx0.e()[2], qx0.e()[3], qy0.e()[0], qy0.e()[1], qy0.e()[2], qy0.e()[3]]).expect("p0 not on curve");
    let p1 = Secp256k1Point::from_u64_arr(&[qx1.e()[0], qx1.e()[1], qx1.e()[2], qx1.e()[3], qy1.e()[0], qy1.e()[1], qy1.e()[2], qy1.e()[3]]).expect("p1 not on curve");
    p0.add(&p1)
}
